function drawText(g, str, x, y, col, scale) {
  col = col || '#fcfcfc'; scale = scale || 1;
  g.fillStyle = col;
  let cx = x;
  for (const ch0 of String(str)) {
    const gl = FONT_GLYPHS[ch0.toUpperCase()];
    if (gl) {
      for (let r = 0; r < 7; r++) {
        const row = gl[r];
        if (!row) continue;
        for (let c = 0; c < 5; c++) if (row & (16 >> c)) g.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += 6 * scale;
  }
}
function textWidth(str, scale) { scale = scale || 1; return String(str).length * 6 * scale - scale; }
function drawTextC(g, str, y, col, scale) { drawText(g, str, Math.round((256 - textWidth(str, scale)) / 2), y, col, scale); }
function drawTextR(g, str, xRight, y, col) { drawText(g, str, xRight - textWidth(str), y, col); }
